_MESSAGES: dict[str, dict[str, str]] = {
    "zh_CN": _ZH,
    "en_US": _EN,
}


def available_languages() -> tuple[str, ...]:
    return tuple(_MESSAGES)


def normalize_language(value: str | None) -> str:
    if not value:
        return DEFAULT_LANGUAGE
    normalized = value.strip().replace("-", "_")
    if normalized.lower() in {"zh", "zh_cn", "zh_hans", "cn", "chinese", "中文"}:
        return "zh_CN"
    if normalized.lower() in {"en", "en_us", "english"}:
        return "en_US"
    return normalized if normalized in _MESSAGES else DEFAULT_LANGUAGE


def current_language() -> str:
    if _active_language is not None:
        return _active_language
    return normalize_language(os.environ.get("FILM_FOUNDRY_LANG"))


def set_language(language: str) -> str:
    global _active_language
    _active_language = normalize_language(language)
    os.environ["FILM_FOUNDRY_LANG"] = _active_language
    return _active_language


def language_label(language: str, *, display_language: str | None = None) -> str:
    code = normalize_language(language)
    return tr(f"language.{code}", language=display_language)


def language_options(*, display_language: str | None = None) -> tuple[str, ...]:
    return tuple(language_label(code, display_language=display_language) for code in available_languages())


def language_from_label(label: str, *, display_language: str | None = None) -> str:
    for code in available_languages():
        if language_label(code, display_language=display_language) == label:
            return code
    return normalize_language(label)


def tr(key: str, *, language: str | None = None) -> str:
    lang = normalize_language(language) if language is not None else current_language()
    return _MESSAGES.get(lang, {}).get(key) or _MESSAGES[DEFAULT_LANGUAGE].get(key) or key
