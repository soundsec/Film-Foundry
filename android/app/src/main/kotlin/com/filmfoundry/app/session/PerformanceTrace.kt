package com.filmfoundry.app.session

import com.filmfoundry.interchange.RecipeJson
import java.io.File
import java.nio.file.Files
import java.nio.file.StandardCopyOption

/** Bounded application diagnostics. No images, paths, recipes, messages or resource IDs. */
class PerformanceTrace(val id: String,private val configuration: Map<String,Any?>,private val clockMs: ()->Long) {
    private val started=clockMs()
    private var ended: Long?=null
    private var state="running"
    private var errorType: String?=null
    private data class Timing(var count: Int=0,var nanos: Long=0,var maximum: Long=0)
    private val timings=linkedMapOf<String,Timing>()
    private val samples=java.util.ArrayDeque<Map<String,Any?>>()
    private val events=java.util.ArrayDeque<Map<String,Any?>>()
    private val peaks=linkedMapOf<String,Double>()
    private var sampleCount=0
    private var eventCount=0
    private val eventTotals=linkedMapOf<String,Int>()
    @Synchronized fun timing(command: String,section: String,nanos: Long) {
        if(ended!=null || nanos<0 || !timingName.matches(command) || !timingName.matches(section)) return
        val key="$command.$section"
        if(key !in timings && timings.size>=96) return
        timings.getOrPut(key){Timing()}.apply { count++;this.nanos+=nanos;maximum=maxOf(maximum,nanos) }
    }
    @Synchronized fun sample(metrics: Map<String,Number>) {
        if(ended!=null) return
        val safe=metrics.filter { it.key in metricKeys && it.value.toDouble().isFinite() }
        safe.forEach { (key,value)->peaks[key]=maxOf(peaks[key] ?: Double.NEGATIVE_INFINITY,value.toDouble()) }
        samples.addLast(mapOf("elapsed_ms" to elapsed())+safe);sampleCount++
        if(samples.size>360) samples.removeFirst()
    }
    @Synchronized fun event(phase: String,index: Int=0,total: Int=0,width: Int=0,height: Int=0,bits: Int=0,quality: Int=0,format: String?=null) {
        if(ended!=null || phase !in eventPhases) return
        eventTotals[phase]=(eventTotals[phase] ?: 0)+1
        events.addLast(mapOf("elapsed_ms" to elapsed(),"phase" to phase,"frame" to index,"total" to total,
            "width" to width,"height" to height,"bits" to bits,"jpeg_quality" to quality,"format" to format?.takeIf { it in setOf("JPEG","PNG","TIFF") }));eventCount++
        if(events.size>256) events.removeFirst()
    }
    @Synchronized fun finish(status: String,error: String?=null) {
        require(status in listOf("completed","paused","failed"))
        if(ended!=null) return
        ended=clockMs();state=status;errorType=error?.takeIf { "[A-Za-z0-9_]{1,80}".toRegex().matches(it) }
    }
    private fun elapsed()=((ended ?: clockMs())-started).coerceAtLeast(0)
    @Synchronized fun snapshot(): Map<String,Any?> = mapOf("schema" to "film_foundry_performance_v1","id" to id,
        "configuration" to configuration.toMap(),"status" to state,"error_type" to errorType,"wall_ms" to elapsed(),
        "operations" to timings.keys.map { it.substringBefore('.') }.distinct(),
        "stage_timings" to timings.mapValues { (_,t)->mapOf("count" to t.count,"total_ms" to t.nanos/1e6,"max_ms" to t.maximum/1e6) },
        "resource_peaks" to peaks.toMap(),"sample_count" to sampleCount,"samples" to samples.toList(),
        "event_count" to eventCount,"event_totals" to eventTotals.toMap(),"events" to events.toList())
    companion object {
        private val timingName=Regex("[a-z0-9_]{1,48}")
        private val metricKeys=setOf("java_heap_bytes","native_heap_bytes","process_cpu_ms","battery_c","battery_percent","thermal_status","screen_interactive")
        private val eventPhases=setOf("forming","developing","registered","scan_start","scan_output","scan_failed","scan_reused","png_saved","jpg_saved","tif_saved","expose","develop_latent","scan","export")
    }
}

/** Only files generated by this feature live here. Atomic snapshots survive process death. */
class PerformanceTraceStore(private val root: File) {
    @Synchronized fun save(trace: PerformanceTrace) {
        require(trace.id.matches(Regex("[a-f0-9-]{36}")))
        check(root.isDirectory || root.mkdirs())
        val pending=File(root,"${trace.id}.pending");val destination=File(root,"${trace.id}.json")
        val text=RecipeJson.text(trace.snapshot());require(text.length<=1048576)
        try {
            pending.writeText(text,Charsets.UTF_8)
            Files.move(pending.toPath(),destination.toPath(),StandardCopyOption.ATOMIC_MOVE,StandardCopyOption.REPLACE_EXISTING)
        } finally { pending.delete() }
        files().drop(20).forEach { it.delete() }
        root.listFiles().orEmpty().filter { it.name.matches(Regex("[a-f0-9-]{36}\\.pending")) }.forEach { it.delete() }
    }
    private fun files()=root.listFiles().orEmpty().filter { it.name.matches(Regex("[a-f0-9-]{36}\\.json")) }.sortedByDescending { it.lastModified() }
    @Synchronized fun records(activeId: String?=null)=files().take(20).mapNotNull { file ->
        runCatching { require(file.length()<=1048576);RecipeJson.objectMap(file.readText(Charsets.UTF_8)) }.getOrNull()?.let {
            if(it["status"]=="running" && it["id"]!=activeId) it+("status" to "interrupted") else it
        }
    }
    @Synchronized fun clear() { files().forEach { check(it.delete()) { "Cannot remove performance record" } } }
}
